#!/usr/bin/env python3
"""Generate src/text_table.inc: the per-character behaviour of the reference text normalizer for every Unicode
code point, so that the C++ normalizer gives the same letters as Python's `text.normalisiere()`.

normalisiere() works character by character on text.lower(): replacement table, NFKD accent stripping (except
ä ö ü ß), whitespace -> " ", everything outside the 52-symbol charset dropped. For each code point c this script
computes the output of that procedure for c alone; the C++ side then maps every input code point through the table
and collapses whitespace. Also emits the Unicode ranges of str.isalpha() and str.isspace() (used by the sentence
splitter, which counts letters).

    python gen_text_table.py > ../src/text_table.inc
"""
import sys
import unicodedata

ZEICHEN = " abcdefghijklmnopqrstuvwxyzäöüß.,?!-'\":;()0123456789"
ID = {c: i + 1 for i, c in enumerate(ZEICHEN)}
ERSATZ = {"’": "'", "‘": "'", "`": "'", "´": "'", "“": '"', "”": '"', "„": '"', "«": '"', "»": '"',
          "–": "-", "—": "-", "…": ".", "ø": "ö", "æ": "ä", "ð": "d", "þ": "th"}


def per_char(ch: str) -> str:
    aus = []
    for c in ch.lower():
        c = ERSATZ.get(c, c)
        if c not in ID and c not in "äöüß":
            c = unicodedata.normalize("NFKD", c)
            c = "".join(x for x in c if not unicodedata.combining(x))
        for x in c:
            if x in ID:
                aus.append(x)
            elif x.isspace():
                aus.append(" ")
    return "".join(aus)


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def cstr(s: str) -> str:
    return '"' + "".join(f"\\x{b:02x}" for b in s.encode("utf-8")) + '"'


def main():
    entries = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        r = per_char(c)
        if r == "" or (r == c and c in ID and len(c) == 1):
            continue                     # dropped, or a charset symbol that maps to itself (handled in code)
        entries.append((cp, r))
    alpha, space = ranges(str.isalpha), ranges(str.isspace)
    w = sys.stdout.write
    w(f"// generated by tools/gen_text_table.py with Python {sys.version.split()[0]}, "
      f"Unicode {unicodedata.unidata_version}; do not edit\n")
    w(f"static const CharMap k_char_map[{len(entries)}] = {{\n")
    for cp, r in entries:
        w(f"    {{0x{cp:05X}, {cstr(r)}}},\n")
    w("};\n")
    w(f"static const CodeRange k_alpha_ranges[{len(alpha)}] = {{\n")
    for a, b in alpha:
        w(f"    {{0x{a:05X}, 0x{b:05X}}},\n")
    w("};\n")
    w(f"static const CodeRange k_space_ranges[{len(space)}] = {{\n")
    for a, b in space:
        w(f"    {{0x{a:05X}, 0x{b:05X}}},\n")
    w("};\n")


if __name__ == "__main__":
    main()
